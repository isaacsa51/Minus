import com.serranoie.app.minus.domain.model.AppColorScheme

fun getAppColorScheme(
    appColorScheme: AppColorScheme,
    isDark: Boolean
): ColorScheme? {
    return when (appColorScheme) {
        AppColorScheme.BRAND -> null
        AppColorScheme.PINK -> if (isDark) pinkDarkScheme else pinkLightScheme
        AppColorScheme.PINK_NEUTRAL -> if (isDark) pinkNeutralDarkScheme else pinkNeutralLightScheme
        AppColorScheme.RED -> if (isDark) redDarkScheme else redLightScheme
        AppColorScheme.RED_NEUTRAL -> if (isDark) redNeutralDarkScheme else redNeutralLightScheme
        AppColorScheme.BLUE -> if (isDark) blueDarkScheme else blueLightScheme
        AppColorScheme.BLUE_NEUTRAL -> if (isDark) blueNeutralDarkScheme else blueNeutralLightScheme
        AppColorScheme.ORANGE -> if (isDark) orangeDarkScheme else orangeLightScheme
        AppColorScheme.ORANGE_NEUTRAL -> if (isDark) orangeNeutralDarkScheme else orangeNeutralLightScheme
        AppColorScheme.YELLOW -> if (isDark) yellowDarkScheme else yellowLightScheme
        AppColorScheme.YELLOW_NEUTRAL -> if (isDark) yellowNeutralDarkScheme else yellowNeutralLightScheme
        AppColorScheme.AQUA -> if (isDark) aquaDarkScheme else aquaLightScheme
        AppColorScheme.AQUA_NEUTRAL -> if (isDark) aquaNeutralDarkScheme else aquaNeutralLightScheme
        AppColorScheme.CYAN -> if (isDark) cyanDarkScheme else cyanLightScheme
        AppColorScheme.CYAN_NEUTRAL -> if (isDark) cyanNeutralDarkScheme else cyanNeutralLightScheme
        AppColorScheme.PURPLE -> if (isDark) purpleDarkScheme else purpleLightScheme
        AppColorScheme.PURPLE_NEUTRAL -> if (isDark) purpleNeutralDarkScheme else purpleNeutralLightScheme
        AppColorScheme.GREEN -> if (isDark) greenDarkScheme else greenLightScheme
    }
}

